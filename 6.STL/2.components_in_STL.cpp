// Main Components in STL
//
// STL mainly consists of:
//
// 1. Iterators
//    - Used to traverse/access elements in containers.
//    - Can be thought of as generalized pointers.
//    - Example: vector.begin(), vector.end()
//
//
// 2. Functors
//    - Objects that can behave like functions.
//    - Can maintain/manage state.
//    - Can accept parameters.
//    - Often used with STL algorithms.
//
//
// 3. Algorithms
//    - Ready-to-use generic operations.
//    - Examples: search, sort, partition, etc.
//
//
// 4. Containers
//    - Data structures provided by the STL to store and organize data.
//
//    Sequence Containers:
//    - vector
//    - list
//    - deque
//
//    Container Adaptors:
//    - stack
//    - queue
//    - priority_queue
//
//
//    Associative Containers:
//    - set
//    - multiset
//    - map
//    - multimap
//    - Usually implemented using balanced search trees.
//
//
//    Unordered Associative Containers:
//    - unordered_set
//    - unordered_multiset
//    - unordered_map
//    - unordered_multimap
//    - Generally implemented using hash tables.
//
//
// A simple way to remember STL:
//
// Containers → store data
// Iterators  → move through data
// Algorithms → work on data
// Functors   → provide behavior/state
//
//
// The next topics will show how these components
// work together in actual STL programs.


